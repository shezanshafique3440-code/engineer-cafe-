import {
  ShoppingBag,
  ClipboardList,
  ChefHat,
  Wallet,
  Utensils,
  Truck,
  Package,
  Users,
  BarChart3,
  Settings,
  FolderTree,
  Ticket,
  Star,
  Mail,
  Sparkles,
  QrCode,
  type LucideIcon,
} from "lucide-react";
const icons: Record<string, LucideIcon> = {
  sale: ShoppingBag,
  orders: ClipboardList,
  kitchen: ChefHat,
  cash: Wallet,
  tables: Utensils,
  delivery: Truck,
  stock: Package,
  team: Users,
  reports: BarChart3,
  settings: Settings,
  categories: FolderTree,
  coupons: Ticket,
  reviews: Star,
  messages: Mail,
  rewards: Sparkles,
  qr: QrCode,
};
export const navigationIcon = (name: string): LucideIcon =>
  icons[name] ?? ClipboardList;
